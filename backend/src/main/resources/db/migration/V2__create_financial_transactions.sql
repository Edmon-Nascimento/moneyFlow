ALTER TABLE categories
    ADD CONSTRAINT categories_id_type_unique UNIQUE (id, type);

CREATE TABLE financial_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    description VARCHAR(200) NOT NULL CHECK (btrim(description) <> ''),
    amount NUMERIC(14, 2) NOT NULL CHECK (amount > 0),
    type VARCHAR(20) NOT NULL CHECK (type IN ('INCOME', 'EXPENSE')),
    transaction_date DATE NOT NULL,
    category_id BIGINT NOT NULL,
    CONSTRAINT financial_transactions_category_type_fk
        FOREIGN KEY (category_id, type) REFERENCES categories (id, type) ON DELETE RESTRICT
);
